"""Turn the simulation CSV into the LaTeX tables of Section 7 of the manuscript.

Usage (from the repository root, after the run of 21 November 2026):

    nice -n 19 /home/claude/venv-dx/bin/python -I docs/manuscrito/llenar_resultados.py \
        <folder of the run>/resultados.csv --commit <hash> > docs/manuscrito/resultados_tablas.tex

Then replace Tables 5, 6 and 7 of main.tex (labels tab:scen, tab:means, tab:diff) with
\\input{resultados_tablas} and check every number against the resumen.md of the same run.

The statistics mirror despacho/sim/correr.py: mean and sample standard deviation across seeds,
paired differences per seed with a 95 % Student t interval (n - 1 degrees of freedom), and the
number of seeds in which despachox is better, equal or worse (|difference| <= 1e-9 counts as equal).
This script only reformats; it adds no statistic that correr.py does not compute.
"""
from __future__ import annotations

import argparse
import csv
import math
import sys
from collections import defaultdict

import numpy as np
from scipy import stats

LOADS = [("holgada", "Light"), ("media", "Medium"), ("alta", "High")]
POLICIES = ["ingenua", "experta", "optimiza_una_vez", "despachox"]
# metric -> (label in the manuscript, higher is better, decimals)
METRICS = {
    "a_tiempo_criticos_pct": ("M1 Critical on time (\\%)", True, 1),
    "perecedero_vencido_pct": ("M2 Perishables expired (\\%)", False, 1),
    "a_tiempo_todos_pct": ("M3 On time, all points (\\%)", True, 1),
    "entregados_pct": ("M4 Delivered within the day (\\%)", True, 1),
    "demanda_no_atendida_pct": ("M5 Requested kg not in good condition (\\%)", False, 1),
    "llegada_media_h": ("M6 Mean order-to-delivery time (h)", False, 2),
    "llegada_max_h": ("M7 Maximum order-to-delivery time (h)", False, 2),
    "peor_punto_h": ("M8 Worst-served point (h)", False, 2),
    "km": ("M9 Fleet kilometres", False, 1),
    "vehiculos_aislados": ("M10 Vehicles left without a way back", False, 1),
    "salidas_emergencia": ("M11 Returns over unsuitable roads", False, 1),
    "recalculos": ("M13 Calls to the optimizer", False, 1),
    "recalculo_medio_s": ("M14 Mean solve time per call (s)", False, 2),
    "recalculo_max_s": ("M14 Maximum solve time per call (s)", False, 2),
}
MAIN_TABLE = ["a_tiempo_criticos_pct", "perecedero_vencido_pct", "a_tiempo_todos_pct", "peor_punto_h", "km"]
DIFFS = [("ingenua", ["a_tiempo_criticos_pct", "perecedero_vencido_pct", "a_tiempo_todos_pct", "peor_punto_h"]),
         ("experta", ["a_tiempo_criticos_pct", "perecedero_vencido_pct", "a_tiempo_todos_pct", "peor_punto_h", "km"]),
         ("optimiza_una_vez", ["a_tiempo_criticos_pct", "a_tiempo_todos_pct"])]


def num(x: float, dec: int) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n.a."
    text = f"{x:.{dec}f}"
    if float(text) == 0:
        text = text.lstrip("-")
    return text.replace("-", "$-$")


def ic95(x):
    """Same computation as despacho.sim.correr.ic95."""
    x = np.asarray([v for v in x if not math.isnan(v)], float)
    n = len(x)
    if n < 2:
        return (float(x.mean()) if n else float("nan"), float("nan"), float("nan"), n)
    half = stats.t.ppf(0.975, n - 1) * x.std(ddof=1) / math.sqrt(n)
    return float(x.mean()), float(x.mean() - half), float(x.mean() + half), n


def read(path):
    rows = defaultdict(dict)          # (load, policy) -> seed -> row
    with open(path, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            rows[(r["carga"], r["politica"])][int(r["semilla"])] = r
    return rows


def col(rows, load, policy, metric):
    seeds = sorted(rows[(load, policy)])
    return [float(rows[(load, policy)][s][metric]) for s in seeds], seeds


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv")
    ap.add_argument("--commit", default="[SIM]")
    args = ap.parse_args(argv)
    rows = read(args.csv)
    loads = [(k, name) for k, name in LOADS if (k, POLICIES[0]) in rows]
    out = []
    w = out.append
    n_seeds = {k: len(rows[(k, POLICIES[0])]) for k, _ in loads}
    errors = sum(int(r.get("fallos_optimizador") or 0) for d in rows.values() for r in d.values())
    w(f"% Generated by docs/manuscrito/llenar_resultados.py from {args.csv}; commit {args.commit}.")
    w(f"% Seeds per load level: {n_seeds}. Optimizer calls that ended in error: {errors}.")
    w("")
    # Table 5: scenarios
    w("\\begin{table}[ht]\n\\centering\n\\small\n\\caption{Scenarios by load level: means across seeds.}\n\\label{tab:scen}")
    w("\\begin{tabular}{l" + "c" * len(loads) + "}\n\\toprule\n & " + " & ".join(n for _, n in loads) + " \\\\\n\\midrule")
    first = POLICIES[0]
    def mean_of(k, field, scale=1.0):
        vals, _ = col(rows, k, first, field)
        return float(np.mean(vals)) / scale
    w("Delivery points (critical) & " + " & ".join(
        f"{mean_of(k, 'puntos'):.0f} ({mean_of(k, 'criticos'):.0f})" for k, _ in loads) + " \\\\")
    w("Orders & " + " & ".join(f"{mean_of(k, 'pedidos'):.0f}" for k, _ in loads) + " \\\\")
    w("Requested mass (t) & " + " & ".join(num(mean_of(k, 'kg_pedidos', 1000.0), 1) for k, _ in loads) + " \\\\")
    w("Vehicles & " + " & ".join(num(mean_of(k, 'vehiculos'), 1) for k, _ in loads) + " \\\\")
    w("Closures (discovered) & " + " & ".join(
        f"{num(mean_of(k, 'cierres'), 1)} ({num(mean_of(k, 'cierres_descubiertos'), 1)})" for k, _ in loads) + " \\\\")
    w("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    # Table 6: means by policy
    w("\\begin{table}[ht]\n\\centering\n\\footnotesize\n\\setlength{\\tabcolsep}{4pt}\n\\caption{Mean (standard deviation across seeds) of each metric "
      "by policy and load level. M1 and M2 are the primary outcomes.}\n\\label{tab:means}")
    w("\\begin{tabular}{llcccc}\n\\toprule\nLoad & Metric & " +
      " & ".join(f"\\code{{{p.replace('_', chr(92) + '_')}}}" for p in POLICIES) + " \\\\")
    for k, name in loads:
        w("\\midrule")
        for i, m in enumerate(MAIN_TABLE):
            label, _, dec = METRICS[m]
            cells = []
            for p in POLICIES:
                x = np.array(col(rows, k, p, m)[0], float)
                cells.append(f"{num(float(np.nanmean(x)), dec)} ({num(float(np.nanstd(x, ddof=1)), dec)})")
            w(f"{name if i == 0 else ''} & {label} & " + " & ".join(cells) + " \\\\")
    w("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    # Table 7: paired differences
    w("\\begin{table}[ht]\n\\centering\n\\footnotesize\n\\setlength{\\tabcolsep}{4pt}\n\\caption{Paired differences of \\code{despachox} against each other "
      "policy: mean [95\\% confidence interval] and better/equal/worse seeds for \\code{despachox}. "
      "Percentage metrics in percentage points.}\n\\label{tab:diff}")
    w("\\begin{tabular}{ll" + "c" * len(loads) + "}\n\\toprule\nComparison & Metric & " +
      " & ".join(n for _, n in loads) + " \\\\")
    for other, metrics in DIFFS:
        w("\\midrule")
        for i, m in enumerate(metrics):
            label, higher_better, dec = METRICS[m]
            cells = []
            for k, _ in loads:
                a, sa = col(rows, k, "despachox", m)
                b, sb = col(rows, k, other, m)
                if sa != sb:
                    raise SystemExit(f"seeds differ between despachox and {other} at load {k}")
                d = [x - y for x, y in zip(a, b)]
                mean, lo, hi, n = ic95(d)
                sign = 1 if higher_better else -1
                valid = [v for v in d if not math.isnan(v)]
                better = sum(sign * v > 1e-9 for v in valid)
                worse = sum(sign * v < -1e-9 for v in valid)
                cells.append("\\begin{tabular}[t]{@{}c@{}}" + f"{num(mean, dec)} [{num(lo, dec)}; {num(hi, dec)}]"
                             + "\\\\" + f"{better}/{n - better - worse}/{worse}" + "\\end{tabular}")
            head = f"$-$ \\code{{{other.replace('_', chr(92) + '_')}}}" if i == 0 else ""
            w(f"{head} & {label.split(' ')[0]} & " + " & ".join(cells) + " \\\\")
    w("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    # Supplementary: the remaining metrics
    w("% Supplementary table: remaining metrics, mean (sd).")
    for k, name in loads:
        for m, (label, _, dec) in METRICS.items():
            if m in MAIN_TABLE:
                continue
            cells = []
            for p in POLICIES:
                x = np.array(col(rows, k, p, m)[0], float)
                cells.append(f"{num(float(np.nanmean(x)), dec)} ({num(float(np.nanstd(x, ddof=1)), dec)})")
            w(f"% {name} & {label} & " + " & ".join(cells) + " \\\\")
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
